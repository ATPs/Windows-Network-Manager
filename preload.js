const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('networkManager', Object.freeze({
  getPrivilegeStatus: () => ipcRenderer.invoke('system:get-privilege-status'),
  restartAsAdministrator: () => ipcRenderer.invoke('system:restart-as-administrator'),
  getNetworkOverview: () => ipcRenderer.invoke('network:get-overview'),
  getWifiProfiles: (input) => ipcRenderer.invoke('wifi:get-profiles', input),
  connectWifi: (input) => ipcRenderer.invoke('wifi:connect', input),
  disconnectWifi: (input) => ipcRenderer.invoke('wifi:disconnect', input),
  previewMetricChange: (input) => ipcRenderer.invoke('metric:preview', input),
  setInterfaceMetric: (input) => ipcRenderer.invoke('metric:set', input),
  getRoutes: () => ipcRenderer.invoke('routes:get'),
  previewAddRoute: (input) => ipcRenderer.invoke('routes:preview-add', input),
  addRoute: (input) => ipcRenderer.invoke('routes:add', input),
  previewRemoveRoute: (input) => ipcRenderer.invoke('routes:preview-remove', input),
  removeRoute: (input) => ipcRenderer.invoke('routes:remove', input),
  previewAdapterState: (input) => ipcRenderer.invoke('adapter:preview-state', input),
  setAdapterState: (input) => ipcRenderer.invoke('adapter:set-state', input),
  listNetworkProfiles: () => ipcRenderer.invoke('profiles:list'),
  saveNetworkProfile: (input) => ipcRenderer.invoke('profiles:save', input),
  deleteNetworkProfile: (profileId) => ipcRenderer.invoke('profiles:delete', { profileId }),
  previewApplyProfile: (profileId) => ipcRenderer.invoke('profiles:preview-apply', { profileId }),
  applyProfile: (input) => ipcRenderer.invoke('profiles:apply', input),
  saveSettings: (input) => ipcRenderer.invoke('settings:save', input),
}));
